    def _record(self, kind: str, payload: dict[str, Any]) -> None:
        self.stream.write(json.dumps({
            "kind": kind,
            "sim_time_ns": self.sim_now_ns,
            "payload": payload,
        }, sort_keys=True, allow_nan=False) + "\n")

    def _clock(self, message: Any) -> None:
        self.sim_now_ns = _time_ns(message.clock)
        if self.sim_now_ns > 0 and self.sim_start_ns is None:
            self.sim_start_ns = self.sim_now_ns

    def _odometry(self, message: Any) -> None:
        if message.header.frame_id != "lio_odom":
            return
        position = message.pose.pose.position
        values = (float(position.x), float(position.y), float(position.z))
        if all(math.isfinite(value) for value in values):
            velocity = tuple(float(value) for value in (
                message.twist.twist.linear.x,
                message.twist.twist.linear.y,
                message.twist.twist.linear.z,
            ))
            if not all(math.isfinite(value) for value in velocity):
                velocity = (0.0, 0.0, 0.0)
            self.latest_odom = {
                "x": values[0], "y": values[1], "z": values[2],
                "vx": velocity[0], "vy": velocity[1], "vz": velocity[2],
            }
            self.latest_odom_stamp_ns = _time_ns(message.header.stamp)
            self._update_localization_watchdog()

    def _ground_truth(self, message: Any) -> None:
        position = message.pose.pose.position
        values = (float(position.x), float(position.y), float(position.z))
        if not all(math.isfinite(value) for value in values):
            return
        velocity = tuple(float(value) for value in (
            message.twist.twist.linear.x,
            message.twist.twist.linear.y,
            message.twist.twist.linear.z,
        ))
        if not all(math.isfinite(value) for value in velocity):
            velocity = (0.0, 0.0, 0.0)
        self.latest_ground_truth = {
            "x": values[0], "y": values[1], "z": values[2],
            "vx": velocity[0], "vy": velocity[1], "vz": velocity[2],
        }
        self.latest_ground_truth_stamp_ns = _time_ns(message.header.stamp)
        self._update_localization_watchdog()
        vehicle_radius = float(self.config.get("vehicle_collision_radius_m", 0.35))
        if not math.isfinite(vehicle_radius) or vehicle_radius <= 0.0:
            self.failure = "vehicle_collision_radius_m must be finite and positive"
            return
        clearance = math.inf
        closest_obstacle_name: str | None = None
        for obstacle in self.config.get("collision_obstacles", []):
            if not isinstance(obstacle, dict):
                continue
            center = obstacle.get("center", [])
            if not _finite_vector(center):
                continue
            point = (values[0], values[1], values[2])
            obstacle_type = str(obstacle.get("type", "box"))
            if obstacle_type == "box":
                half_extents = obstacle.get("half_extents", [])
                if not _finite_vector(half_extents) or any(float(value) <= 0.0 for value in half_extents):
                    continue
                q = [abs(point[index] - float(center[index])) - float(half_extents[index]) for index in range(3)]
                outside = math.sqrt(sum(max(value, 0.0) ** 2 for value in q))
                signed_distance = outside + min(max(q), 0.0)
            elif obstacle_type == "cylinder":
                radius = float(obstacle.get("radius_m", 0.0))
                half_height = float(obstacle.get("half_height_m", 0.0))
                if not math.isfinite(radius) or not math.isfinite(half_height) or radius <= 0.0 or half_height <= 0.0:
                    continue
                radial_gap = math.hypot(point[0] - float(center[0]), point[1] - float(center[1])) - radius
                vertical_gap = abs(point[2] - float(center[2])) - half_height
                signed_distance = math.hypot(max(radial_gap, 0.0), max(vertical_gap, 0.0)) + min(max(radial_gap, vertical_gap), 0.0)
            else:
                continue
            obstacle_clearance = signed_distance - vehicle_radius
            if obstacle_clearance < clearance:
                clearance = obstacle_clearance
                closest_obstacle_name = str(obstacle.get("name", "")) or None
        if math.isfinite(clearance):
            if (self.minimum_collision_clearance_m is None or
                    clearance < self.minimum_collision_clearance_m):
                self.minimum_collision_clearance_m = clearance
                self.minimum_collision_obstacle_name = closest_obstacle_name
            in_collision = clearance <= 0.0
            if in_collision:
                self.collision_count += 1
            if in_collision and not self._in_collision:
                self.collision_event_count += 1
            self._in_collision = in_collision
        obstacle = self.config.get("pillar_center_enu")
        if int(self.config.get("pillar_waypoint_index", 3)) < 0 or not _finite_vector(obstacle):
            return
        radius = float(self.config.get("pillar_radius_m", 0.55))
        clearance = math.hypot(values[0] - float(obstacle[0]), values[1] - float(obstacle[1])) - radius
        self.actual_min_clearance_m = clearance if self.actual_min_clearance_m is None else min(self.actual_min_clearance_m, clearance)

    @staticmethod
    def _cloud_roi_count(message: Any, *, sensor_frame: bool) -> int:
        """Count finite obstacle samples without retaining a second point cloud."""
        try:
            from sensor_msgs_py import point_cloud2
            count = 0
            for point in point_cloud2.read_points(
                message, field_names=("x", "y", "z"), skip_nans=True
            ):
                x, y, z = (float(point[0]), float(point[1]), float(point[2]))
                if not all(math.isfinite(value) for value in (x, y, z)):
                    continue
                if sensor_frame:
                    # no_path wall is at x=1 and spans y/z; this ROI avoids
                    # using the floor as the obstacle evidence.
                    inside = 0.5 <= x <= 1.6 and abs(y) <= 20.0 and -3.5 <= z <= 8.5
                else:
                    inside = 0.5 <= x <= 1.5 and abs(y) <= 20.0 and 0.0 <= z <= 12.0
                if inside:
                    count += 1
            return count
        except (ImportError, AttributeError, TypeError, ValueError):
            return 0

    def _raw_lidar(self, message: Any) -> None:
        self.raw_lidar_scan_count += 1
        count = self._cloud_roi_count(message, sensor_frame=True)
        self.raw_lidar_roi_max_points = max(self.raw_lidar_roi_max_points, count)
        if count >= 20:
            self.raw_lidar_roi_scan_count += 1
            if self.raw_lidar_roi_scan_count == 1:
                self._record("map_evidence", {
                    "kind": "raw_lidar_obstacle_roi",
                    "points": count,
                    "frame_id": str(message.header.frame_id),
                })

    def _occupied_map(self, message: Any) -> None:
        count = self._cloud_roi_count(message, sensor_frame=False)
        self.occupied_roi_max_points = max(self.occupied_roi_max_points, count)
        if count >= 5:
            self.occupied_scan_count += 1
            if self.occupied_scan_count == 1:
                self._record("map_evidence", {
                    "kind": "occupied_voxel_obstacle_roi",
                    "points": count,
                    "frame_id": str(message.header.frame_id),
                })

    def _update_localization_watchdog(self) -> None:
        if not self.post_takeoff_mode_entered or self.latest_odom is None or self.latest_ground_truth is None:
            return
        if self.latest_odom_stamp_ns is None or self.latest_ground_truth_stamp_ns is None:
            return
        if abs(self.latest_odom_stamp_ns - self.latest_ground_truth_stamp_ns) > 40_000_000:
            return
        lio = self.latest_odom
        truth = self.latest_ground_truth
        if self.lio_gt_origin_offset is None:
            self.lio_gt_origin_offset = tuple(lio[key] - truth[key] for key in ("x", "y", "z"))
            self._record("event", {"name": "ground_truth_watchdog_started"})
            return
        position_error = math.sqrt(sum(
            (lio[key] - truth[key] - self.lio_gt_origin_offset[index]) ** 2
            for index, key in enumerate(("x", "y", "z"))
        ))
        self.max_lio_position_residual_m = max(self.max_lio_position_residual_m, position_error)
        if len(self.lio_position_residual_samples) < 20000:
            self.lio_position_residual_samples.append(position_error)
        velocity_error = math.sqrt(sum(
            (lio[key] - truth[key]) ** 2 for key in ("vx", "vy", "vz")
        ))
        self.max_lio_velocity_residual_m_s = max(
            self.max_lio_velocity_residual_m_s, velocity_error
        )
        # Negative localization profiles must hand control back before the
        # product watchdog's 0.5 m residual limit is crossed.  Keep the
        # nominal watchdog at 0.5 m, but arm the fail-closed harness at 0.45 m
        # so the navigation mode can hand over to POSCTL while the estimator
        # is still inside the acceptance envelope.
        expected_failure = str(self.config.get("expected_outcome", "complete")) == "fail_closed"
        threshold_exceeded = (position_error > (0.45 if expected_failure else 0.5) or
                              velocity_error > 1.0)
        if threshold_exceeded:
            if self.localization_divergence_started_ns is None:
                self.localization_divergence_started_ns = self.sim_now_ns
                self.first_divergence_event = {
                    "classification": "LOCALIZATION_DIVERGENCE",
                    "timestamp_sim_ns": self.sim_now_ns,
                    "position_residual_m": position_error,
                    "velocity_residual_m_s": velocity_error,
                }
                self._record("event", self.first_divergence_event)
            elif (expected_failure or
                  self.sim_now_ns - self.localization_divergence_started_ns >= 500_000_000):
                if not self.localization_divergence_failure:
                    self.localization_divergence_failure = True
                    self.failure = "LOCALIZATION_DIVERGENCE"
                    self._record_handover_request(
                        "localization_divergence",
                        {"position_residual_m": position_error,
                         "velocity_residual_m_s": velocity_error},
                    )
        else:
            self.localization_divergence_started_ns = None

    def _status(self, message: Any) -> None:
        nav_state = int(message.nav_state)
        armed = int(message.arming_state) == int(self.VehicleStatus.ARMING_STATE_ARMED)
        mask = int(message.can_set_nav_states_mask)
        if self.external_mode_id is None:
            for candidate in range(
                int(self.VehicleStatus.NAVIGATION_STATE_EXTERNAL1),
                int(self.VehicleStatus.NAVIGATION_STATE_EXTERNAL8) + 1,
            ):
                if mask & (1 << candidate):
                    self.external_mode_id = candidate
                    event = {"name": "external_mode_discovered", "mode_id": candidate}
                    self.events.append(event)
                    self._record("event", event)
                    break
        mode_was_active = getattr(self, "mode_active", self.mode_entered)
        if self.external_mode_id is not None and nav_state == self.external_mode_id:
            if not mode_was_active:
                event = {"name": "external_mode_entered", "mode_id": self.external_mode_id}
                self.events.append(event)
                self._record("event", event)
                self.mode_entered_sim_ns = self.sim_now_ns
            self.mode_entered = True
            self.mode_active = True
            if (
                getattr(self, "execution", "single_goal") == "mission"
                and getattr(self, "takeoff_requested", False)
                and getattr(self, "takeoff_observed", False)
            ):
                self.post_takeoff_mode_entered = True
        active_before_status = mode_was_active
        if active_before_status and self.exit_requested and int(message.executor_in_charge) == 0 and not self.mode_exit_observed:
            self.mode_exit_observed = True
            self.exit_request_sim_ns = getattr(self, "sim_now_ns", 0)
            event = {"name": "external_mode_exit_observed", "nav_state": nav_state, "executor_in_charge": int(message.executor_in_charge)}
            self.events.append(event)
            self._record("event", event)
        elif active_before_status and nav_state != self.external_mode_id and not self.mode_exit_observed:
            self.mode_exit_observed = True
            self.exit_request_sim_ns = getattr(self, "sim_now_ns", 0)
            event = {"name": "external_mode_exit_observed", "nav_state": nav_state}
            self.events.append(event)
            self._record("event", event)
            self.mode_active = False
            if (
                self.execution == "mission"
                and self.takeoff_observed
                and not self.mission_complete_observed
                and str(self.config.get("expected_outcome", "complete")) != "fail_closed"
            ):
                self.mission_unexpected_exit_observed = True
                self.failure = "External Mode exited before mission completion"
                self._record_handover_request(
                    "unexpected_external_mode_exit",
                    {"nav_state": nav_state,
                     "executor_in_charge": int(message.executor_in_charge)},
                )
        elif active_before_status and nav_state != self.external_mode_id and not self.mode_active:
            self.mode_active = False
        if self.mode_entered and nav_state == int(self.VehicleStatus.NAVIGATION_STATE_AUTO_RTL):
            self.unexpected_rtl = True
        # Keep PX4 failsafe evidence separate from an application handover.
        # A failsafe after a completed mission remains diagnostic evidence but
        # does not retroactively turn a successful mission into a failure.
        if bool(message.failsafe) and not getattr(self, "mission_complete_observed", False):
            self.failsafe_seen = True
        self.armed_seen = self.armed_seen or armed
        self.latest_status = {
            "timestamp_us": int(message.timestamp),
            "arming_state": int(message.arming_state),
            "nav_state": nav_state,
            "failsafe": bool(message.failsafe),
            "pre_flight_checks_pass": bool(message.pre_flight_checks_pass),
            "executor_in_charge": int(message.executor_in_charge),
            "can_set_nav_states_mask": mask,
        }
        if nav_state != self.previous_nav_state:
            self._record("vehicle_status", self.latest_status)
        self.previous_nav_state = nav_state

    def _trajectory(self, message: Any) -> None:
        self.trajectory_received += 1
        if not bool(message.success):
            self.trajectory_failure_count += 1
            same_request = (
                self.latest_trajectory.get("mission_id") == str(message.mission_id) and
                self.latest_trajectory.get("waypoint_index") == int(message.waypoint_index) and
                self.latest_trajectory.get("request_id") == int(message.request_id)
            )
            if same_request and self.latest_trajectory.get("trajectory_role") == 0:
                self.pending_nominal_failure_ns = self.sim_now_ns
            self._record("trajectory_failure", {
                "mission_id": str(message.mission_id),
                "waypoint_index": int(message.waypoint_index),
                "request_id": int(message.request_id),
                "failure_code": int(message.failure_code),
                "world_generation": int(message.world_generation),
                "world_revision": int(message.world_revision),
            })
            return
        self.trajectory_success_count += 1
        role_key = str(int(message.trajectory_role))
        safety_key = str(int(message.safety_plan_kind))
        self.trajectory_role_counts[role_key] = self.trajectory_role_counts.get(role_key, 0) + 1
        self.safety_kind_counts[safety_key] = self.safety_kind_counts.get(safety_key, 0) + 1
        points = [
            (float(point.x), float(point.y), float(point.z)) for point in message.position
        ]
        pillar = self.config.get("pillar_center_enu", [-4.5, 2.5, 3.0])
        pillar_distance = None
        if _finite_vector(pillar):
            pillar_distance = min(
                math.hypot(point[0] - float(pillar[0]), point[1] - float(pillar[1]))
                for point in points
            ) if points else None
        self.latest_trajectory = {
            "mission_id": str(message.mission_id),
            "waypoint_index": int(message.waypoint_index),
            "request_id": int(message.request_id),
            "world_generation": int(message.world_generation),
            "world_revision": int(message.world_revision),
            "duration_s": float(message.duration_s),
            "point_count": len(message.position),
            # Preserve the committed local plan for post-flight visualization
            # and continuity analysis.  The cap keeps scenario.jsonl bounded
            # even if a planner publishes an unexpectedly dense trajectory.
            "position_points": [list(point) for point in points[:512]],
            "velocity_points": [
                [float(vector.x), float(vector.y), float(vector.z)]
                for vector in list(message.velocity)[:512]
            ],
            "pillar_min_distance_m": pillar_distance,
            "trajectory_role": int(message.trajectory_role),
            "safety_plan_kind": int(message.safety_plan_kind),
        }
        self.trajectory_history.append(dict(self.latest_trajectory))
        if len(self.trajectory_history) > 4096:
            del self.trajectory_history[:len(self.trajectory_history) - 4096]
        if int(message.trajectory_role) == 1 and self.pending_nominal_failure_ns is not None:
            self.safety_transition_count += 1
            self.fallback_latencies_ms.append(
                max(0.0, (self.sim_now_ns - self.pending_nominal_failure_ns) / 1e6)
            )
            self.pending_nominal_failure_ns = None
        elif int(message.trajectory_role) != 1:
            # A retry that returns to nominal execution is not a fallback;
            # do not let a later unrelated safety trajectory inherit it.
            self.pending_nominal_failure_ns = None
        record_key = (self.latest_trajectory["mission_id"], self.latest_trajectory["waypoint_index"])
        if self.execution == "mission" and self.latest_trajectory["waypoint_index"] >= 0:
            record_index = self._trajectory_record_indices.get(record_key)
            if record_index is None:
                self._trajectory_record_indices[record_key] = len(self.trajectory_records)
                self.trajectory_records.append(dict(self.latest_trajectory))
            else:
                self.trajectory_records[record_index] = dict(self.latest_trajectory)
        elif len(self.trajectory_records) < 128:
            self.trajectory_records.append(dict(self.latest_trajectory))
        self._record("trajectory", self.latest_trajectory)


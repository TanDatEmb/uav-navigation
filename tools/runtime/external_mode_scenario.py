def _time_ns(value: Any) -> int:
    return int(value.sec) * 1_000_000_000 + int(value.nanosec)


def _finite_vector(values: Any, size: int = 3) -> bool:
    try:
        return len(values) == size and all(math.isfinite(float(value)) for value in values)
    except (TypeError, ValueError):
        return False


def _reject_unknown_keys(value: Any, allowed: set[str], scope: str) -> None:
    if not isinstance(value, dict):
        raise ValueError(f"{scope} must be a mapping")
    unknown = sorted(set(value) - allowed)
    if unknown:
        raise ValueError(f"unsupported {scope} field(s): {', '.join(unknown)}")


def _json_vector(values: Any) -> list[float | None]:
    """Keep intentional PX4 NaN sentinel values JSON-serializable."""
    result: list[float | None] = []
    for value in values:
        number = float(value)
        result.append(number if math.isfinite(number) else None)
    return result


def _json_number(value: Any) -> float | None:
    """Keep intentional scalar NaN sentinel values JSON-serializable."""
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return number if math.isfinite(number) else None


def _json_xyz(value: Any) -> list[float | None]:
    """Serialize a ROS Point/Vector3 while preserving diagnostic NaN sentinels."""
    try:
        return _json_vector([value.x, value.y, value.z])
    except (AttributeError, TypeError, ValueError):
        return [None, None, None]


def _heading_from_quaternion(quaternion: Any) -> float | None:
    """Return ENU yaw from a ROS quaternion without trusting its scale."""
    try:
        x = float(quaternion.x)
        y = float(quaternion.y)
        z = float(quaternion.z)
        w = float(quaternion.w)
    except (AttributeError, TypeError, ValueError):
        return None
    norm = math.sqrt(x * x + y * y + z * z + w * w)
    if not math.isfinite(norm) or norm <= 1.0e-9:
        return None
    x, y, z, w = (value / norm for value in (x, y, z, w))
    return math.atan2(
        2.0 * (w * z + x * y),
        1.0 - 2.0 * (y * y + z * z),
    )


def _normalize_quaternion_xyzw(values: Any) -> list[float] | None:
    try:
        q = [float(value) for value in values]
    except (TypeError, ValueError):
        return None
    if len(q) != 4 or not all(math.isfinite(value) for value in q):
        return None
    norm = math.sqrt(sum(value * value for value in q))
    if not math.isfinite(norm) or norm <= 1.0e-9:
        return None
    return [value / norm for value in q]


def _quaternion_inverse_xyzw(values: list[float]) -> list[float]:
    return [-values[0], -values[1], -values[2], values[3]]


def _quaternion_multiply_xyzw(left: list[float], right: list[float]) -> list[float]:
    lx, ly, lz, lw = left
    rx, ry, rz, rw = right
    return [
        lw * rx + lx * rw + ly * rz - lz * ry,
        lw * ry - lx * rz + ly * rw + lz * rx,
        lw * rz + lx * ry - ly * rx + lz * rw,
        lw * rw - lx * rx - ly * ry - lz * rz,
    ]


def _rotation_matrix_from_quaternion_xyzw(values: list[float]) -> list[list[float]]:
    x, y, z, w = values
    return [
        [1.0 - 2.0 * (y * y + z * z), 2.0 * (x * y - z * w), 2.0 * (x * z + y * w)],
        [2.0 * (x * y + z * w), 1.0 - 2.0 * (x * x + z * z), 2.0 * (y * z - x * w)],
        [2.0 * (x * z - y * w), 2.0 * (y * z + x * w), 1.0 - 2.0 * (x * x + y * y)],
    ]


def _matrix_vector(matrix: list[list[float]], vector: list[float]) -> list[float]:
    return [sum(matrix[row][column] * vector[column] for column in range(3)) for row in range(3)]


def _slerp_quaternion_xyzw(
    left: list[float], right: list[float], alpha: float
) -> list[float] | None:
    """Interpolate two unit quaternions without extrapolating pose data."""
    first = _normalize_quaternion_xyzw(left)
    second = _normalize_quaternion_xyzw(right)
    if first is None or second is None or not math.isfinite(alpha):
        return None
    dot = sum(first[index] * second[index] for index in range(4))
    if dot < 0.0:
        second = [-value for value in second]
        dot = -dot
    dot = min(1.0, max(-1.0, dot))
    if dot > 0.9995:
        return _normalize_quaternion_xyzw([
            first[index] + alpha * (second[index] - first[index])
            for index in range(4)
        ])
    theta = math.acos(dot)
    sine_theta = math.sin(theta)
    if not math.isfinite(sine_theta) or abs(sine_theta) <= 1.0e-12:
        return None
    first_weight = math.sin((1.0 - alpha) * theta) / sine_theta
    second_weight = math.sin(alpha * theta) / sine_theta
    return _normalize_quaternion_xyzw([
        first_weight * first[index] + second_weight * second[index]
        for index in range(4)
    ])


def _interpolate_pose_history(
    history: list[dict[str, Any]], target_stamp_ns: int
) -> dict[str, Any] | None:
    """Sample a pose history at a source timestamp using interpolation only."""
    ordered = sorted(
        (sample for sample in history if sample.get("source_stamp_ns") is not None),
        key=lambda sample: int(sample["source_stamp_ns"]),
    )
    if not ordered:
        return None
    for sample in ordered:
        if int(sample["source_stamp_ns"]) == target_stamp_ns:
            return dict(sample)
    bracket = None
    for left, right in zip(ordered, ordered[1:]):
        left_stamp = int(left["source_stamp_ns"])
        right_stamp = int(right["source_stamp_ns"])
        if left_stamp <= target_stamp_ns <= right_stamp and right_stamp > left_stamp:
            bracket = (left, right)
            break
    if bracket is None:
        return None
    left, right = bracket
    left_stamp = int(left["source_stamp_ns"])
    right_stamp = int(right["source_stamp_ns"])
    for key in ("localization_epoch", "frame_id", "child_frame_id"):
        left_value = left.get(key)
        right_value = right.get(key)
        if left_value is not None and right_value is not None and left_value != right_value:
            return None
    alpha = (target_stamp_ns - left_stamp) / float(right_stamp - left_stamp)
    position = [
        (1.0 - alpha) * float(left[axis]) + alpha * float(right[axis])
        for axis in ("x", "y", "z")
    ]
    quaternion = _slerp_quaternion_xyzw(
        list(left.get("q_xyzw", [])), list(right.get("q_xyzw", [])), alpha)
    if quaternion is None or not _finite_vector(position):
        return None
    result = dict(left)
    result.update({
        "x": position[0], "y": position[1], "z": position[2],
        "q_xyzw": quaternion,
        "source_stamp_ns": int(target_stamp_ns),
        "source_bracket_start_ns": left_stamp,
        "source_bracket_end_ns": right_stamp,
        "source_bracket_gap_ns": right_stamp - left_stamp,
    })
    receive_stamps = (
        left.get("receive_stamp_ns"), right.get("receive_stamp_ns"))
    if all(stamp is not None for stamp in receive_stamps):
        result["receive_stamp_ns"] = int(round(
            (1.0 - alpha) * int(receive_stamps[0]) +
            alpha * int(receive_stamps[1])))
    return result


def _percentile(values: list[float], fraction: float) -> float | None:
    if not values:
        return None
    ordered = sorted(values)
    index = min(len(ordered) - 1, round((len(ordered) - 1) * fraction))
    return ordered[index]


def _speed_contract_failures(
    expected_max_velocity_mps: float | None,
    required_measured_speed_mps: float | None,
    setpoint_speed_samples: list[float],
    measured_speed_samples: list[float],
) -> list[str]:
    failures: list[str] = []
    setpoint_max = max(setpoint_speed_samples, default=0.0)
    if expected_max_velocity_mps is not None and (
        not math.isfinite(float(expected_max_velocity_mps))
        or setpoint_max > float(expected_max_velocity_mps) + 0.10
    ):
        failures.append("PX4 velocity setpoint exceeded mission velocity limit")
    measured_p95 = _percentile(measured_speed_samples, 0.95)
    if required_measured_speed_mps is not None and (
        measured_p95 is None
        or measured_p95 < float(required_measured_speed_mps) - 0.10
    ):
        failures.append(
            "measured speed p95 did not reach required cruise speed: "
            f"required {float(required_measured_speed_mps):.2f} m/s, "
            f"observed {measured_p95} m/s"
        )
    return failures


def _fail_closed_contract_failures(
    *,
    mission_complete_observed: bool,
    mode_failure_observed: bool,
    safety_pause_observed: bool,
    executable_trajectory_count: int,
) -> list[str]:
    """Check the negative mission contract without requiring a rejection sample.

    A rejected terminal command is useful diagnostic evidence, but it is not
    guaranteed when the planner fails before producing a candidate.  The
    safety contract is instead: the mission must not complete, the runtime
    must expose a terminal fail-closed state, and no executable trajectory
    authority may have been published.
    """
    failures: list[str] = []
    if mission_complete_observed:
        failures.append("fail-closed scenario unexpectedly completed mission")
    if not (mode_failure_observed or safety_pause_observed):
        failures.append(
            "fail-closed scenario observed neither ModeCompleted failure "
            "nor terminal safety pause"
        )
    if executable_trajectory_count > 0:
        failures.append(
            "fail-closed scenario exposed executable trajectory authority"
        )
    return failures



"""PX4-native External Mode acceptance scenario.

The default scenario publishes a bounded goal to the product-owned planning
boundary and observes the trajectory generated by ``navigation_runtime`` at
the PX4 TrajectorySetpoint boundary. A deterministic stationary fixture is
still available for isolated adapter tests. The scenario selects
the registered external mode from VehicleStatus, arms, enters the mode, then
hands control back to PX4 POSCTL. It never lands or disarms the vehicle, and it
does not publish OffboardControlMode or use the Offboard mode path.
"""

